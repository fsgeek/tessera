# EXPLORATORY PROBE 2026-10-04 — non-discharging; not part of any registration
# Derives a DEPTH SLICE of cap_cc02_d.spthy by DELETING whole rules (never editing one).
# Deleting rules only removes behaviours, so any trace (attack) found in a slice is a trace
# of the full model; a "verified" in a slice says nothing about the full model.
#   python3 slice.py depth0|depth1|depth2 [noD|bytesD|attOnly]   (depth2 = full depth)
import re, sys
W12 = r'WrapCheck1_12|WrapOne_.*_12|W1_.*_12(_[HD])?|WrapTwo_.*_12|W2_.*_12(_[HD])?|AttestCheck1_L2|SUnwrap_12|StandingPathIn_L2'
W01 = r'WrapCheck1_01|WrapOne_.*_01|W1_.*_01(_[HD])?|WrapTwo_.*_01|W2_.*_01(_[HD])?|AttestCheck1_L1|SUnwrap_01|StandingPathIn_L1'
which = sys.argv[1]
# GUIDED slices (falsification only): additionally delete dsks (_D) reductions
#   noD      : every stage check uses only checksign's honest-key reduction
#   bytesD   : the dsks reduction kept ONLY on BYTES checks (the C-Q3 route)
guide = sys.argv[2] if len(sys.argv) > 2 else ''
drop = {'depth0': W01 + '|' + W12, 'depth1': W12, 'depth2': r'NO_RULE_MATCHES_THIS'}[which]
if guide == 'noD':    drop += r'|\w+_chk\d_\w+_D'
if guide == 'bytesD': drop += r'|\w+_chk\d_poss\w+_D'
#   attOnly  : bytesD, AND the honest processes other than Attester deleted
if guide == 'attOnly': drop += r'|\w+_chk\d_poss\w+_D|ShipIssuer|RefuseIssuer|ForeignIssuer|Wrapper'
#   wit      : noD, plus RefuseIssuer, ForeignIssuer, Wrapper deleted (for witness reachability)
if guide == 'wit': drop += r'|\w+_chk\d_\w+_D|RefuseIssuer|ForeignIssuer|Wrapper'
if guide: which = which + '.' + guide
s = open('cap_cc02_d.spthy').read()
parts = re.split(r'(?m)^(?=rule |lemma |/\* =|// |#ifdef|#else|#endif|end\s*$)', s)
out, dropped = [], []
for p in parts:
    m = re.match(r'rule (\w+):', p)
    if m and re.fullmatch(drop, m.group(1)):
        dropped.append(m.group(1)); continue
    out.append(p)
txt = ''.join(out)
first, rest = txt.split('\n', 1)
banner = (f"{first}\n// GENERATED by slice.py {which} from cap_cc02_d.spthy; do not edit.\n"
          f"// Rules deleted ({len(dropped)}): {', '.join(dropped)}\n")
open(f'cap_cc02_d.{which}.spthy', 'w').write(banner + rest)
print(which, 'dropped', len(dropped))
