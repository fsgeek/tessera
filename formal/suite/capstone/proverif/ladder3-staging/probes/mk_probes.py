#!/usr/bin/env python3
# PROBES 2026-10-01 (builder, ladder-3 staging) -- NOT ladder results, NOT registered queries.
# Adapts the cross-family reviewer's probe (dev/codex/scratch/capstone_d_noninnermost_attest.pv,
# made from ladder-2 capstone_d.pv) to the BF-5-repaired model, by the SAME edits:
#   - a private probe channel; SUnwrap additionally reports (aid, lyrOut, fbIA);
#   - ProbeJudge fires ProbeNonInnermostStanding(a, l) iff the frame at (a, l) is
#     itself an OT_WRAPPER wrap() frame whose inner frame is OT_ATTEST AND the standing
#     path reported ESTABLISHED for (a, l) on estCh;
#   - the registered query list replaced by the probe query plus positive controls.
import re, sys, os
H = os.path.dirname(os.path.abspath(__file__))
def make(src, dst, controls):
    t = open(os.path.join(H, '..', src)).read()
    t = t.replace("free scopeEnvelope: channel [private].",
                  "free scopeEnvelope: channel [private].\nfree probeFrameCh: channel [private].\n"
                  "event ProbeNonInnermostStanding(bitstring,bitstring).", 1)
    i = t.index("(* ---- C-Q1 link 1a")
    j = t.index("(* ==================================================================== *)\n(* ==== THE FIXTURE'S HONEST")
    q = "query a:bitstring, l:bitstring; event(ProbeNonInnermostStanding(a,l)).\n" + controls + "\n"
    t = t[:i] + q + t[j:]
    old = "  out(sStageCh, (aid, lyrOut, fbIA, sgIA, fbIB, sgIB))."
    assert t.count(old) == 1
    t = t.replace(old, "  ( out(sStageCh, (aid, lyrOut, fbIA, sgIA, fbIB, sgIB)) | out(probeFrameCh, (aid, lyrOut, fbIA)) ).")
    pj = ("let ProbeJudge =\n"
          "  in(probeFrameCh, (a:bitstring, l:bitstring, fb:bitstring));\n"
          "  let framed(=OT_WRAPPER, al, id, kfp, mh, cv, wrap(cvi, (f1:bitstring,s1:bitstring,f2:bitstring,s2:bitstring))) = fb in\n"
          "  let framed(=OT_ATTEST, al2, id2, kfp2, mh2, cv2, payload2) = f1 in\n"
          "  in(estCh, (=a, =l, k:pkey, t:bitstring, ad:bitstring));\n"
          "  event ProbeNonInnermostStanding(a,l).\n\n")
    t = t.replace("(* ---- C-Q6 conjunct 2 and the honest standing witness", pj + "(* ---- C-Q6 conjunct 2 and the honest standing witness", 1)
    t = t.replace("  | !StandingJudge | !ScopeAgreementJudge", "  | !ProbeJudge | !StandingJudge | !ScopeAgreementJudge", 1)
    assert "!ProbeJudge" in t
    open(os.path.join(H, dst), 'w').write(
        "(* PROBE, NOT A LADDER FILE: generated by probes/mk_probes.py from ladder3-staging/%s *)\n" % src + t)
CTRL = ("query a: bitstring, t: bitstring, k: pkey, co: bitstring; event(EstablishedWrapped(a, L1, t, k, co, ESTABLISHED)).\n"
        "query a: bitstring, t: bitstring, k: pkey, co: bitstring; event(EstablishedWrapped(a, L2, t, k, co, ESTABLISHED)).\n"
        "query a: bitstring; event(HonestWrappedStandingAgreed(a, L1)).\n"
        "query a: bitstring; event(HonestWrappedStandingAgreed(a, L2)).\n"
        "query k: pkey, aid: bitstring; event(HonestStandingEstablished(k, aid)).")
make("capstone_d.pv", "probe_d_noninnermost_attest_l3.pv", CTRL)
make("capstone.pv", "probe_a_noninnermost_attest_l3.pv", CTRL)
# CONTROL: the same probe on the UNREPAIRED ladder-2 model (case (a)), to show the probe is
# sensitive in strict as the reviewer showed it in (d).  Source: ../capstone.pv (blob a9fb7da1...).
make("../capstone.pv", "probe_a_noninnermost_attest_L2CONTROL.pv", CTRL)
