def uncomment(s):
 out=[]; i=0; depth=0
 while i<len(s):
  if s[i:i+2]=='(*': depth+=1;out.extend('  ');i+=2
  elif s[i:i+2]=='*)' and depth:depth-=1;out.extend('  ');i+=2
  else:out.append(s[i] if not depth or s[i]=='\n' else ' ');i+=1
 assert depth==0
 return ''.join(out)
def noqueries(s):
 # Independent boundary: declarations consist of lines from query to first period,
 # verified against comment-stripped source; preserve every other original byte.
 clean=uncomment(s); spans=list(re.finditer(r'(?m)^query\b[^.]*\.',clean))
 for m in reversed(spans): s=s[:m.start()]+s[m.end():]
 return uncomment(s)
def parts(s):
 pre,sep,tail=s.partition('\n  ( !out(honestKeyCh')
 assert sep
 block='!out(honestKeyCh'+tail
 assert block.rstrip().endswith(')')
 block=block.rstrip()[:-1]
 # All actual components are single calls or names, with no nested process operator.
 comps=[x.strip() for x in block.split('|')]
 assert all(re.fullmatch(r'!\w+(?:\([^;|]*\))?',x) for x in comps)
 return pre,comps
